            <details>
              <summary>¿Qué es una certificación de competencia laboral?<span class="faq-icon">+</span></summary>
              <div class="faq-body">Es un reconocimiento oficial que acredita que una persona puede demostrar, en situaciones reales, los conocimientos, destrezas, habilidades, actitudes, hábitos y valores necesarios para un área de trabajo específica. A diferencia de un curso o diplomado, no certifica que estudiaste algo, sino que puedes hacerlo. En el caso del EC0679, certifica que puedes usar el inglés de forma efectiva en un entorno laboral.</div>
            </details>
          </div>


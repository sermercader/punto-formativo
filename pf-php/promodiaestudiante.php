              <div class="faq-body">El CONOCER es el Consejo Nacional de Normalización y Certificación de Competencias Laborales, un organismo del Gobierno de México coordinado por la SEP. Su función es establecer estándares oficiales que certifican que una persona tiene las competencias necesarias para desempeñarse en un área laboral específica. Una certificación emitida por el CONOCER tiene validez en todo el territorio nacional.</div>
